import type { EvalReport } from './harness';
import { relative } from 'node:path';
import { outcomeMix, type CaseVariance, type Variance } from './repeat';

// evals/results.md, always from the replay pass. Tool calls, cost and time are the live
// run's, read from each recording, so replaying unchanged code reproduces the same file.

const secs = (v: number | null) => (v === null ? '—' : `${(v / 1000).toFixed(1)} s`);
const cell = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function renderReport(r: EvalReport, variance: Variance | null = null): string {
  const passed = r.results.filter((x) => x.pass).length;
  const recorded = r.results.filter((x) => x.tool_calls !== null);
  const estimated = recorded.some((x) => x.cost_estimated);
  const money = (v: number | null, est: boolean) => (v === null ? 'n/a' : `${est ? '~' : ''}$${v.toFixed(4)}`);
  const total = recorded.reduce((s, x) => s + (x.cost_usd ?? 0), 0);
  const runs = [...new Set(recorded.map((x) => `\`${x.model}\` via ${x.transport}`))].join(', ') || 'none recorded yet';

  const lines = [
    '# Eval results',
    '',
    `Generated by \`npm run eval:replay\`. **${passed} of ${r.results.length} cases pass.** Recorded runs: ${runs}. Agent cost of the recorded runs: ${money(total, estimated)}${estimated ? ' (~ marks Claude Code’s own estimate; those runs used a subscription, not API billing)' : ''}.`,
    '',
    'Grading is deterministic: detection is compared with the planted ground truth, and each plan is checked for an allowed outcome, a required action and no forbidden action. Every proposed action is then pushed through the real approval path (forged capability, wrong payload hash, stale data, double approval).',
    '',
  ];
  const earlier = r.results.filter((x) => x.earlier_prompt).map((x) => x.id);
  if (earlier.length) lines.push(`> † Recorded with an earlier prompt or tool definitions: ${earlier.join(', ')}. They replay through today's checks; re-record them to see what the current prompt does.`, '');
  if (r.extraction_missing.length) lines.push(`> ${r.extraction_missing.length} emails had no cached extraction (${r.extraction_missing.join(', ')}). Run \`npm run extract\` to fill the cache.`, '');
  lines.push('| Case | What it tests | Result | Outcome | Actions | Tool calls | Cost | Time |', '|---|---|---|---|---|---:|---:|---:|');
  for (const x of r.results) {
    const ran = x.tool_calls !== null;
    lines.push(`| ${x.id}${x.earlier_prompt ? ' †' : ''} | ${cell(x.tests)} | ${x.pass ? 'pass' : '**fail**'} | ${x.outcome ?? '—'} | ${x.actions.join(', ') || '—'} | ${x.tool_calls ?? '—'} | ${ran ? money(x.cost_usd, x.cost_estimated) : '—'} | ${secs(x.duration_ms)} |`);
  }
  const failures = r.results.filter((x) => !x.pass);
  if (failures.length) {
    lines.push('', '## Failures', '');
    for (const x of failures) {
      const reasons = [...x.detection.reasons, ...(x.decision?.reasons ?? []), ...(x.guardrails?.reasons ?? [])];
      lines.push(`- **${x.id}**: ${reasons.map(cell).join('; ')}`);
    }
  }
  if (variance?.cases.length) {
    // Cases can be re-run on their own, so date and setup go in a column only when they differ.
    const day = (c: CaseVariance) => c.recorded_at.slice(0, 10);
    const setup = (c: CaseVariance) => `\`${c.model}\` via ${c.transport}, ${c.effort} effort`;
    const days = [...new Set(variance.cases.map(day))];
    const setups = [...new Set(variance.cases.map(setup))];
    const runs = [...new Set(variance.cases.map((c) => c.runs))];
    const extra = [...(days.length > 1 ? [{ head: 'Run on', of: day }] : []), ...(setups.length > 1 ? [{ head: 'Setup', of: setup }] : [])];
    lines.push(
      '',
      '## Variance: repeated live runs',
      '',
      `Each decision case run ${runs.length === 1 ? `${runs[0]} times` : 'several times'} live${days.length === 1 ? ` on ${days[0]}` : ''}${setups.length === 1 ? ` (${setups[0]})` : ''} and graded like the table above. The table above grades one committed recording per case; this one shows how often a fresh run passes.`,
      '',
      `| Case | Passed | Outcomes |${extra.map((e) => ` ${e.head} |`).join('')}`,
      `|---|---:|---|${extra.map(() => '---|').join('')}`,
      ...variance.cases.map((c) => `| ${c.id} | ${c.passes}/${c.runs} | ${outcomeMix(c.outcomes)} |${extra.map((e) => ` ${e.of(c)} |`).join('')}`),
    );
    const failing = variance.cases.filter((c) => c.failures.length);
    // Links are relative to evals/, where results.md lives.
    const link = (path: string | null) => (path ? ` ([recording](${relative('evals', path)}))` : ' (recording not kept)');
    if (failing.length) lines.push('', ...failing.flatMap((c) => c.failures.map((f) => `- **${c.id}** run ${f.run}: ${cell(f.reason)}${link(f.recording)}`)));
  }
  return lines.join('\n') + '\n';
}

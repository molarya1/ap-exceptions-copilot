import type { EvalReport } from './harness';

// evals/results.md. Replay reports the live run's tool calls, cost and time from the
// recording, so a replay of unchanged code reproduces the live report exactly.

const money = (v: number | null) => (v === null ? 'n/a' : `$${v.toFixed(4)}`);
const secs = (v: number | null) => (v === null ? '' : `${(v / 1000).toFixed(1)} s`);
const cell = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function renderReport(r: EvalReport): string {
  const passed = r.results.filter((x) => x.pass).length;
  const cost = r.results.reduce((s, x) => s + (x.cost_usd ?? 0), 0);
  const lines = [
    '# Eval results',
    '',
    `Generated by \`npm run eval${r.mode === 'replay' ? ':replay' : ''}\` (${r.mode} mode, model \`${r.model}\`). **${passed} of ${r.results.length} cases pass.** Agent cost for the recorded runs: ${money(cost)}.`,
    '',
    'Grading is deterministic: detection is compared with the planted ground truth, and each plan is checked for an allowed outcome, a required action and no forbidden action. Every proposed action is then pushed through the real approval path (forged capability, wrong payload hash, stale data, double approval).',
    '',
  ];
  if (r.extraction_missing.length) lines.push(`> ${r.extraction_missing.length} emails had no cached extraction (${r.extraction_missing.join(', ')}). Run \`npm run eval\` with a key to fill the cache.`, '');
  lines.push('| Case | What it tests | Result | Outcome | Actions | Tool calls | Cost | Time |', '|---|---|---|---|---|---:|---:|---:|');
  for (const x of r.results) {
    lines.push(`| ${x.id} | ${cell(x.tests)} | ${x.pass ? 'pass' : '**fail**'} | ${x.outcome ?? '—'} | ${x.actions.join(', ') || '—'} | ${x.tool_calls ?? '—'} | ${x.tool_calls === null ? '—' : money(x.cost_usd)} | ${secs(x.duration_ms) || '—'} |`);
  }
  const failures = r.results.filter((x) => !x.pass);
  if (failures.length) {
    lines.push('', '## Failures', '');
    for (const x of failures) {
      const reasons = [...x.detection.reasons, ...(x.decision?.reasons ?? []), ...(x.guardrails?.reasons ?? [])];
      lines.push(`- **${x.id}**: ${reasons.map(cell).join('; ')}`);
    }
  }
  return lines.join('\n') + '\n';
}

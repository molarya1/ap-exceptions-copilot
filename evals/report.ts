import type { EvalReport } from './harness';

// evals/results.md, always from the replay pass. Tool calls, cost and time are the live
// run's, read from each recording, so replaying unchanged code reproduces the same file.

const secs = (v: number | null) => (v === null ? '—' : `${(v / 1000).toFixed(1)} s`);
const cell = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function renderReport(r: EvalReport): string {
  const passed = r.results.filter((x) => x.pass).length;
  const recorded = r.results.filter((x) => x.tool_calls !== null);
  const estimated = recorded.some((x) => x.cost_estimated);
  const money = (v: number | null, est: boolean) => (v === null ? 'n/a' : `${est ? '~' : ''}$${v.toFixed(4)}`);
  const total = recorded.reduce((s, x) => s + (x.cost_usd ?? 0), 0);
  const runs = [...new Set(recorded.map((x) => `\`${x.model}\` via ${x.transport}`))].join(', ') || 'none recorded yet';

  const lines = [
    '# Eval results',
    '',
    `Generated by \`npm run eval:replay\`. **${passed} of ${r.results.length} cases pass.** Recorded runs: ${runs}. Agent cost of the recorded runs: ${money(total, estimated)}${estimated ? ' (~ marks Claude Code’s own estimate; those runs used a subscription, not API billing)' : ''}.`,
    '',
    'Grading is deterministic: detection is compared with the planted ground truth, and each plan is checked for an allowed outcome, a required action and no forbidden action. Every proposed action is then pushed through the real approval path (forged capability, wrong payload hash, stale data, double approval).',
    '',
  ];
  if (r.extraction_missing.length) lines.push(`> ${r.extraction_missing.length} emails had no cached extraction (${r.extraction_missing.join(', ')}). Run \`npm run extract\` to fill the cache.`, '');
  lines.push('| Case | What it tests | Result | Outcome | Actions | Tool calls | Cost | Time |', '|---|---|---|---|---|---:|---:|---:|');
  for (const x of r.results) {
    const ran = x.tool_calls !== null;
    lines.push(`| ${x.id} | ${cell(x.tests)} | ${x.pass ? 'pass' : '**fail**'} | ${x.outcome ?? '—'} | ${x.actions.join(', ') || '—'} | ${x.tool_calls ?? '—'} | ${ran ? money(x.cost_usd, x.cost_estimated) : '—'} | ${secs(x.duration_ms)} |`);
  }
  const failures = r.results.filter((x) => !x.pass);
  if (failures.length) {
    lines.push('', '## Failures', '');
    for (const x of failures) {
      const reasons = [...x.detection.reasons, ...(x.decision?.reasons ?? []), ...(x.guardrails?.reasons ?? [])];
      lines.push(`- **${x.id}**: ${reasons.map(cell).join('; ')}`);
    }
  }
  return lines.join('\n') + '\n';
}
